const LANG_KEY = 'w3c-lang';

function detectLang() {
    try {
        const saved = localStorage.getItem(LANG_KEY);
        if (saved && I18N[saved]) return saved;
    } catch { /* localStorage zablokowany — zostaje wykrywanie z przeglądarki */ }
    return (navigator.language || '').toLowerCase().startsWith('pl') ? 'pl' : 'en';
}

let LANG = detectLang();

/** t('klucz', { n: 5 }) — podstawia {n} w tekście. */
function t(key, vars) {
    let s = I18N[LANG][key] ?? I18N.pl[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
    return s;
}

